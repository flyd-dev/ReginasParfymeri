export function kategorinavn(slug: string, navnFraButikken: string): string {
  const fast = KORTNAVN[slug]
  if (fast) return fast
  const liten = navnFraButikken.toLocaleLowerCase('nb-NO')
  return liten.charAt(0).toLocaleUpperCase('nb-NO') + liten.slice(1)
}
